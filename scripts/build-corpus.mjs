// Reads src/rag/docs/**/*.md into src/rag/corpus.js so the Worker bundle
// does not import Markdown. The markdown files stay the editable source.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const docsDir = path.join(root, "src", "rag", "docs");
const outFile = path.join(root, "src", "rag", "corpus.js");
const ID = /^[a-z0-9-]{1,36}$/;
const FOLDER = /^(operacao|coordenacao)$/;

function walk(dir) {
  const files = [];
  for (const entry of fs.readdirSync(dir, {withFileTypes: true}).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else if (entry.name.endsWith(".md")) files.push(full);
  }
  return files;
}
export function parseDocument(raw, label) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/.exec(String(raw).trimStart());
  if (!match) throw new Error("Missing frontmatter in " + label);
  const meta = {};
  for (const line of match[1].split(/\r?\n/)) {
    if (!line.trim()) continue;
    const pair = /^([a-z]+):\s*(.*)$/.exec(line);
    if (!pair) throw new Error("Bad frontmatter in " + label);
    meta[pair[1]] = pair[2].trim();
  }
  if (!ID.test(meta.id || "") || !FOLDER.test(meta.folder || "") || !meta.title || meta.title.length > 120) {
    throw new Error("Invalid document header in " + label);
  }
  const text = match[2].trim();
  if (!text) throw new Error("Empty document " + label);
  return {id: meta.id, title: meta.title, folder: meta.folder, text};
}
export function loadMarkdownCorpus(dir = docsDir) {
  const documents = walk(dir).map(file => parseDocument(fs.readFileSync(file, "utf8"), path.relative(root, file)));
  const ids = new Set();
  for (const doc of documents) {
    if (ids.has(doc.id)) throw new Error("Duplicate document id " + doc.id);
    ids.add(doc.id);
  }
  return documents;
}
export function renderCorpus(documents) {
  return "// Generated by scripts/build-corpus.mjs from src/rag/docs. Do not edit by hand.\nexport const DOCUMENTS = " +
    JSON.stringify(documents, null, 2) + ";\n";
}
function isDirectRun() {
  const entry = process.argv[1];
  return Boolean(entry) && import.meta.url === pathToFileURL(path.resolve(entry)).href;
}
if (isDirectRun()) {
  const rendered = renderCorpus(loadMarkdownCorpus());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
    if (current !== rendered) {
      console.error("src/rag/corpus.js is stale. Run: npm run corpus:build");
      process.exit(1);
    }
  } else {
    fs.writeFileSync(outFile, rendered);
    console.log("Wrote " + path.relative(root, outFile));
  }
}
